#include <iostream>
using namespace std;

int main() {
    cout << 7 / 2 << endl;       // Output: 3
    cout << 7 % 2 << endl;        // Output: 1
    cout << 7.0 / 2 << endl;      // Output: 3.5
    cout << (5 == 5) << endl;     // Output: 1
    cout << (5 != 5) << endl;     // Output: 0

    int x = 5;
    cout << x++ << " " << x << endl;   // Output: 5 6

    return 0;
}