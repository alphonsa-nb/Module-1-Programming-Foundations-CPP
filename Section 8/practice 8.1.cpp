//Print 1 to 10

#include <iostream>
using namespace std;
int main() {
    for (int i = 1; i <= 10; i++) {
    cout << i << " ";}
    cout << endl;
    return 0;
}

//print 10 to 1

#include <iostream>
using namespace std;
int main() {
    for (int i = 10; i >= 1; i--) {
    cout << i << " ";
    }
    cout << endl;
    return 0;
}

